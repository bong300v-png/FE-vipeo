export type I18nKey = keyof typeof dictionary.en;

export function isLocale(value: string | null | undefined): value is Locale {
  return !!value && locales.includes(value as Locale);
}

export function getInitialLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const lang = navigator.language.toLowerCase();
  return lang.startsWith("vi") ? "vi" : "en";
}

export function getStoredLocale(): Locale {
  if (typeof localStorage === "undefined") return "en";
  const stored = localStorage.getItem("vipeo:locale");
  return isLocale(stored) ? stored : getInitialLocale();
}

export function setStoredLocale(locale: Locale) {
  localStorage.setItem("vipeo:locale", locale);
  window.dispatchEvent(new Event("vipeo:locale-change"));
}

export function t(locale: Locale, key: I18nKey): string {
  return dictionary[locale][key] || dictionary.en[key];
}

export function tx(locale: Locale, text: string): string {
  return locale === "vi" ? viText[text] || text : text;
}
